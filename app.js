let currentLanguage = "de";
let toastTimer;

const translationNodes = document.querySelectorAll("[data-i18n]");
const placeholderNodes = document.querySelectorAll("[data-i18n-placeholder]");
const languageButtons = document.querySelectorAll("[data-lang]");
const description = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const nextLanguage = translations[language] ? language : "de";
  const copy = translations[nextLanguage];
  currentLanguage = nextLanguage;

  document.documentElement.lang = nextLanguage;
  document.title = copy.metaTitle;
  description?.setAttribute("content", copy.metaDescription);

  translationNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key] !== undefined) node.textContent = copy[key];
  });

  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (copy[key] !== undefined) node.setAttribute("placeholder", copy[key]);
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === nextLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.querySelectorAll(".dialog-close, .toast button").forEach((button) => {
    button.setAttribute("aria-label", copy.close);
  });

  try {
    localStorage.setItem("anspruch-language", nextLanguage);
  } catch {
    // The page remains fully functional when storage is disabled.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

function getInitialLanguage() {
  try {
    const saved = localStorage.getItem("anspruch-language");
    if (saved && translations[saved]) return saved;
  } catch {
    // Fall through to browser language.
  }

  const browserLanguage = navigator.language?.slice(0, 2).toLowerCase();
  return translations[browserLanguage] ? browserLanguage : "de";
}

function validateForm(form) {
  const email = form.elements.email;
  const birthYear = form.elements.birthYear;
  const consent = form.elements.consent;
  let valid = true;

  const emailValid = email.validity.valid && email.value.trim().length > 3;
  email.closest(".field").classList.toggle("has-error", !emailValid);
  email.setAttribute("aria-invalid", String(!emailValid));
  valid = emailValid && valid;

  const yearValid = Boolean(birthYear.value);
  birthYear.closest(".field").classList.toggle("has-error", !yearValid);
  birthYear.setAttribute("aria-invalid", String(!yearValid));
  valid = yearValid && valid;

  const consentError = form.querySelector(".consent-error");
  consentError.classList.toggle("visible", !consent.checked);
  consent.setAttribute("aria-invalid", String(!consent.checked));
  valid = consent.checked && valid;

  if (!valid) {
    form.querySelector('[aria-invalid="true"]')?.focus();
  }

  return valid;
}

async function submitLead(form) {
  if (!validateForm(form)) return;
  if (form.elements.website.value) return;

  const button = form.querySelector(".submit-button");
  const originalText = button.querySelector("span").textContent;
  button.classList.add("loading");
  button.disabled = true;
  button.querySelector("span").textContent = "…";

  const payload = {
    email: form.elements.email.value.trim(),
    birthYear: form.elements.birthYear.value,
    language: currentLanguage,
    consent: true,
    consentedAt: new Date().toISOString(),
  };

  const endpoint = document.querySelector('meta[name="lead-endpoint"]')?.content.trim();

  try {
    if (endpoint) {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(payload),
      });

      if (!response.ok) throw new Error(`Lead endpoint returned ${response.status}`);
    } else {
      // Preview mode: the production endpoint is intentionally configured outside source control.
      await new Promise((resolve) => window.setTimeout(resolve, 450));
    }

    form.reset();
    showToast();
  } catch (error) {
    console.error(error);
    window.alert(translations[currentLanguage].formError);
  } finally {
    button.classList.remove("loading");
    button.disabled = false;
    button.querySelector("span").textContent = originalText;
  }
}

document.querySelectorAll(".lead-form").forEach((form) => {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    submitLead(form);
  });

  form.querySelectorAll("input, select").forEach((field) => {
    field.addEventListener("input", () => {
      field.closest(".field")?.classList.remove("has-error");
      if (field.name === "consent") {
        form.querySelector(".consent-error")?.classList.remove("visible");
      }
    });
  });
});

const toast = document.querySelector(".toast");

function showToast() {
  window.clearTimeout(toastTimer);
  toast.classList.add("visible");
  toastTimer = window.setTimeout(() => toast.classList.remove("visible"), 6000);
}

toast.querySelector("button").addEventListener("click", () => {
  window.clearTimeout(toastTimer);
  toast.classList.remove("visible");
});

