export function generateRandomEmail() {
  const company = COMPANIES[Math.floor(Math.random() * COMPANIES.length)];
  const numItems = Math.floor(Math.random() * 3) + 2;
  const selectedItems = [];
  const shuffled = [...COMPONENT_POOL].sort(() => 0.5 - Math.random());

  for (let i = 0; i < numItems; i++) {
    const item = shuffled[i];
    const qty = (Math.floor(Math.random() * 10) + 1) * (item.unit === 'метров' || item.unit === 'тонн' ? 100 : 5);
    selectedItems.push({
      ...item,
      quantity: qty
    });
  }

  const itemsListText = selectedItems
    .map((it, idx) => `${idx + 1}. ${it.name} — ${it.quantity} ${it.unit}`)
    .join('\n');

  const subject = `Запрос КП на поставку материалов (${company.name})`;
  const body = `Здравствуйте, уважаемые партнеры!

Просим рассчитать коммерческое предложение на поставку следующих позиций с учетом доставки в г. ${company.city}:

${itemsListText}

Просьба указать в КП:
- Цены с НДС 20%
- Сроки поставки и условия оплаты
- Срок действия ценового предложения

Дедлайн ответа: в течение 2 рабочих дней.

С уважением,
${company.person}
${company.name}
Тел: ${company.phone}
Email: ${company.email}
ИНН: ${company.inn}`;

  return {
    subject,
    from: `${company.person} <${company.email}>`,
    sender_name: company.person,
    sender_company: company.name,
    sender_phone: company.phone,
    sender_email: company.email,
    sender_inn: company.inn,
    body
  };
}
