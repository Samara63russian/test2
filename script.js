const supportedLanguages = ["de", "fr", "it"];
let currentLanguage = "de";
let currentModal = null;

function getValue(object, path) {
  return path.split(".").reduce((value, key) => value?.[key], object);
}

function getInitialLanguage() {
  const params = new URLSearchParams(window.location.search);
  const queryLanguage = params.get("lang");
  if (supportedLanguages.includes(queryLanguage)) return queryLanguage;

  const savedLanguage = localStorage.getItem("anspruch-language");
  if (supportedLanguages.includes(savedLanguage)) return savedLanguage;

  const browserLanguage = navigator.language?.slice(0, 2).toLowerCase();
  return supportedLanguages.includes(browserLanguage) ? browserLanguage : "de";
}

function setLanguage(language, updateUrl = true) {
  if (!supportedLanguages.includes(language)) return;
  currentLanguage = language;
  const dictionary = translations[language];

  document.documentElement.lang = language;
  document.title = dictionary.meta.title;
  document.querySelector('meta[name="description"]').content = dictionary.meta.description;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getValue(dictionary, element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = getValue(dictionary, element.dataset.i18nPlaceholder);
    if (typeof value === "string") element.placeholder = value;
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });

  document.querySelector(".language-switcher").setAttribute(
    "aria-label",
    language === "de" ? "Sprache" : language === "fr" ? "Langue" : "Lingua",
  );
  document.querySelector(".modal-close").setAttribute("aria-label", dictionary.a11y.close);

  localStorage.setItem("anspruch-language", language);

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    window.history.replaceState({}, "", url);
  }

  clearForms();
  if (currentModal) renderModal(currentModal);
}

function clearForms() {
  document.querySelectorAll("[data-lead-form]").forEach((form) => {
    form.querySelectorAll(".field-error").forEach((error) => {
      error.textContent = "";
    });
    form.querySelectorAll(".field").forEach((field) => field.classList.remove("is-invalid"));
    form.querySelector(".form-status").textContent = "";
  });
}

function validateForm(form) {
  const dictionary = translations[currentLanguage].form;
  const email = form.elements.email;
  const birthYear = form.elements.birthYear;
  const consent = form.elements.consent;
  let isValid = true;

  const setFieldError = (field, message) => {
    field.closest(".field")?.classList.toggle("is-invalid", Boolean(message));
    form.querySelector(`[data-error-for="${field.name}"]`).textContent = message;
    if (message) isValid = false;
  };

  setFieldError(
    email,
    email.validity.valid && email.value.trim() ? "" : dictionary.emailError,
  );
  setFieldError(birthYear, birthYear.value ? "" : dictionary.yearError);

  const consentError = form.querySelector('[data-error-for="consent"]');
  consentError.textContent = consent.checked ? "" : dictionary.consentError;
  if (!consent.checked) isValid = false;

  return isValid;
}

function handleFormSubmit(event) {
  event.preventDefault();
  const form = event.currentTarget;
  const status = form.querySelector(".form-status");
  status.textContent = "";

  if (!validateForm(form)) {
    form.querySelector(".is-invalid input, .is-invalid select, input[name='consent']:not(:checked)")?.focus();
    return;
  }

  const payload = {
    email: form.elements.email.value.trim(),
    birthYear: form.elements.birthYear.value,
    consent: form.elements.consent.checked,
    language: currentLanguage,
    source: form.closest(".final-cta") ? "footer" : "hero",
  };

  /*
   * Integration point: listen for `anspruch:lead` and forward the payload
   * to the selected consent-aware email provider or backend.
   */
  window.dispatchEvent(new CustomEvent("anspruch:lead", { detail: payload }));
  status.textContent = translations[currentLanguage].form.success;
  form.reset();
}

function renderModal(type) {
  const content = legalContent[currentLanguage][type];
  if (!content) return;
  document.querySelector("#modal-title").textContent = content.title;
  document.querySelector("#modal-content").innerHTML = content.body;
}

function openModal(type) {
  const modal = document.querySelector("#legal-modal");
  currentModal = type;
  renderModal(type);
  document.body.classList.add("modal-open");
  modal.showModal();
}

function closeModal() {
  const modal = document.querySelector("#legal-modal");
  modal.close();
  document.body.classList.remove("modal-open");
  currentModal = null;
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.querySelectorAll("[data-lead-form]").forEach((form) => {
  form.addEventListener("submit", handleFormSubmit);
  form.querySelectorAll("input, select").forEach((field) => {
    field.addEventListener("input", () => {
      if (field.name === "consent") {
        form.querySelector('[data-error-for="consent"]').textContent = "";
      } else {
        field.closest(".field")?.classList.remove("is-invalid");
        form.querySelector(`[data-error-for="${field.name}"]`).textContent = "";
      }
    });
  });
});

document.querySelectorAll("[data-modal-open]").forEach((button) => {
  button.addEventListener("click", () => openModal(button.dataset.modalOpen));
});

document.querySelector(".modal-close").addEventListener("click", closeModal);
document.querySelector("#legal-modal").addEventListener("click", (event) => {
  if (event.target === event.currentTarget) closeModal();
});
document.querySelector("#legal-modal").addEventListener("close", () => {
  document.body.classList.remove("modal-open");
  currentModal = null;
});

document.querySelectorAll(".faq-list details").forEach((item) => {
  item.addEventListener("toggle", () => {
    if (!item.open) return;
    document.querySelectorAll(".faq-list details[open]").forEach((otherItem) => {
      if (otherItem !== item) otherItem.open = false;
    });
  });
});

